-- =====================================================================
-- 고객 상품 조회 캐시의 revision (PostgreSQL, DR-37)
--
-- cache-revision.sql (MySQL) 과 같은 일을 PostgreSQL 에서 한다.
-- local-pg 프로필의 ddl-auto: update 는 데이터가 있는 테이블에 NOT NULL 컬럼을 기본값 없이 더하다 실패하므로,
-- 앱을 띄우기 전에 이 스크립트를 먼저 실행한다.
--
-- 주의: 앱의 miss 경로는 MySQL 기본 격리 수준(REPEATABLE READ)에 기대어 revision 과 결과를 한 스냅샷으로 읽는다.
-- PostgreSQL 기본(READ COMMITTED)은 문장마다 스냅샷이라, PostgreSQL 로 운영하려면 격리 수준을 따로 정해야 한다 (DR-37).
--
-- 실행
--   docker exec -i docker-postgres-1 psql -U application -d loopers -v ON_ERROR_STOP=1 < docs/week5/cache-revision-pg.sql
-- =====================================================================

ALTER TABLE brand   ADD COLUMN IF NOT EXISTS revision bigint NOT NULL DEFAULT 0;
ALTER TABLE product ADD COLUMN IF NOT EXISTS revision bigint NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS catalog_revision (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(50)              NOT NULL,
    revision   bigint                   NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    deleted_at timestamp(6) with time zone,
    CONSTRAINT ux_catalog_revision_name UNIQUE (name)
);

INSERT INTO catalog_revision (name, revision, created_at, updated_at, deleted_at)
VALUES ('product_list_latest', 0, now(), now(), NULL)
ON CONFLICT (name) DO NOTHING;
