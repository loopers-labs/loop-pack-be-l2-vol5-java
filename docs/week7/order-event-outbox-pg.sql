-- 순서: 새 앱(Outbox 기록)을 띄우기 전에 실행한다 (order-event-outbox.sql 머리말과 같다).
--
-- 실행
--   docker exec -i docker-postgres-1 psql -U application -d loopers -v ON_ERROR_STOP=1 < docs/week7/order-event-outbox-pg.sql
-- =====================================================================

CREATE TABLE IF NOT EXISTS order_event_outbox (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id            varchar(100)                NOT NULL,
    order_id            bigint                      NOT NULL,
    event_type          varchar(50)                 NOT NULL,
    schema_version      integer                     NOT NULL,
    message_key         varchar(64)                 NOT NULL,
    payload             text                        NOT NULL,
    status              varchar(20)                 NOT NULL,
    attempt_count       integer                     NOT NULL,
    failure_count       integer                     NOT NULL,
    next_attempt_at     timestamp(6) with time zone NOT NULL,
    last_error          varchar(500),
    published_at        timestamp(6) with time zone,
    published_partition integer,
    published_offset    bigint,
    created_at          timestamp(6) with time zone NOT NULL,
    updated_at          timestamp(6) with time zone NOT NULL,
    deleted_at          timestamp(6) with time zone,
    CONSTRAINT ux_order_event_outbox_event UNIQUE (event_id)
);

CREATE INDEX IF NOT EXISTS ix_order_event_outbox_due ON order_event_outbox (status, next_attempt_at, id);
